-- referencia legada do modelo fisico, nao e executada pelo docker
-- o schema ativo do mvp e criado e alterado pelas migrations do django
BEGIN;


CREATE TABLE Cliente (
    id_cliente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100) NOT NULL,
    telefone   VARCHAR(20) NOT NULL,
    endereco   VARCHAR(200)
);

CREATE TABLE Usuario (
    id_usuario      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login           VARCHAR(50) NOT NULL UNIQUE,
    senha           VARCHAR(255) NOT NULL,
    primeiro_acesso BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE Receita (
    id_receita            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(100) NOT NULL,
    rendimento_quantidade DECIMAL(10,2),
    custo_calculado       DECIMAL(10,2) NOT NULL DEFAULT 0
);

CREATE TABLE Produto (
    id_produto  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receita_id  INT REFERENCES Receita(id_receita) ON DELETE SET NULL,
    nome        VARCHAR(100) NOT NULL,
    preco_venda DECIMAL(10,2) NOT NULL
);

CREATE TABLE Ingrediente (
    id_ingrediente        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(100) NOT NULL,
    quantidade_disponivel DECIMAL(10,2),
    custo_unitario        DECIMAL(10,2),
    data_validade         DATE,
    quantidade_minima     DECIMAL(10,2)
);

CREATE TABLE Pedido (
    id_pedido        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       INT,
    tipo             VARCHAR(20) NOT NULL,
    subtipo          VARCHAR(20),
    status           VARCHAR(20) NOT NULL DEFAULT 'pedido_feito',
    data_entrega     DATE,
    horario_entrega  TIME,
    valor_total      DECIMAL(10,2) NOT NULL DEFAULT 0,
    valor_sinal      DECIMAL(10,2) NOT NULL DEFAULT 0,
    endereco_entrega VARCHAR(200),
    forma_pagamento  VARCHAR(30),
    CONSTRAINT FK_Pedido_Cliente
        FOREIGN KEY (cliente_id) REFERENCES Cliente(id_cliente)
        ON DELETE RESTRICT
);

CREATE TABLE Item_Pedido (
    id_item_pedido  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id      INT,
    receita_id      INT REFERENCES Receita(id_receita) ON DELETE RESTRICT,
    pedido_id       INT NOT NULL,
    quantidade      INT,
    preco_unitario  DECIMAL(10,2) NOT NULL,
    custo_unitario  DECIMAL(10,2),
    recheio         VARCHAR(100),
    decoracao       VARCHAR(200),
    quantidade_peso DECIMAL(10,2),
    CONSTRAINT FK_Item_Pedido_Produto
        FOREIGN KEY (produto_id) REFERENCES Produto(id_produto)
        ON DELETE RESTRICT,
    CONSTRAINT FK_Item_Pedido_Pedido
        FOREIGN KEY (pedido_id) REFERENCES Pedido(id_pedido)
        ON DELETE CASCADE
);

CREATE TABLE Agenda (
    id_agenda INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id INT NOT NULL,
    descricao VARCHAR(255),
    data_hora TIMESTAMP,
    CONSTRAINT FK_Agenda_Pedido
        FOREIGN KEY (pedido_id) REFERENCES Pedido(id_pedido)
);

CREATE TABLE Cancelamento (
    id_cancelamento   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id         INT NOT NULL,
    destino           VARCHAR(20),
    data_cancelamento DATE,
    CONSTRAINT FK_Cancelamento_Pedido
        FOREIGN KEY (pedido_id) REFERENCES Pedido(id_pedido)
);

CREATE TABLE Transacao (
    id_transacao INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id    INT NOT NULL,
    valor        DECIMAL(10,2),
    tipo         VARCHAR(20),
    data         TIMESTAMP,
    CONSTRAINT FK_Transacao_Pedido
        FOREIGN KEY (pedido_id) REFERENCES Pedido(id_pedido)
);

CREATE TABLE Estoque (
    id_estoque            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto            INT NOT NULL,
    quantidade_disponivel DECIMAL(10,2) NOT NULL,
    data_validade         DATE,
    custo                 DECIMAL(10,2),
    CONSTRAINT FK_Estoque_Produto
        FOREIGN KEY (id_produto) REFERENCES Produto(id_produto)
);

CREATE TABLE Receita_Produto (
    id_receita_produto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_receita     INT NOT NULL,
    id_produto     INT NOT NULL,
    quantidade     DECIMAL(10,3) NOT NULL,
    unidade_medida VARCHAR(20),
    custo_unitario DECIMAL(10,2),
    CONSTRAINT UQ_Receita_Produto UNIQUE (id_receita, id_produto),
    -- remove o vinculo ao excluir a receita ou o produto relacionado
    CONSTRAINT FK_Receita_Produto_Receita
        FOREIGN KEY (id_receita) REFERENCES Receita(id_receita) ON DELETE CASCADE,
    CONSTRAINT FK_Receita_Produto_Produto
        FOREIGN KEY (id_produto) REFERENCES Produto(id_produto) ON DELETE CASCADE
);

CREATE TABLE Ingrediente_Receita (
    id_ingrediente_receita INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receita_id            INT NOT NULL,
    ingrediente_id        INT NOT NULL,
    quantidade_necessaria DECIMAL(10,2) NOT NULL,
    CONSTRAINT UQ_Ingrediente_Receita UNIQUE (ingrediente_id, receita_id),
    -- remove os componentes ao excluir a receita
    CONSTRAINT FK_Ingrediente_Receita_Receita
        FOREIGN KEY (receita_id) REFERENCES Receita(id_receita) ON DELETE CASCADE,
    CONSTRAINT FK_Ingrediente_Receita_Ingrediente
        FOREIGN KEY (ingrediente_id) REFERENCES Ingrediente(id_ingrediente)
);


COMMIT;
